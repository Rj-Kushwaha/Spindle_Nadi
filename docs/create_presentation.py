"""Build the project presentation using measured synthetic-data results."""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import PP_ALIGN, MSO_ANCHOR
from pptx.util import Inches, Pt

from data.generate_data import DEFAULT_OUTPUT, generate_dataset
from ml.features import REQUIRED_SENSOR_COLUMNS
from ml.pipeline import SpindleNadiPipeline

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "assets" / "Spindle_Nadi_Demo.pptx"
BG = RGBColor(11, 17, 22)
PANEL = RGBColor(18, 30, 37)
TEXT = RGBColor(238, 245, 247)
MUTED = RGBColor(154, 173, 181)
ACCENT = RGBColor(114, 215, 189)
YELLOW = RGBColor(255, 200, 87)
RED = RGBColor(255, 100, 124)
FONT = "Aptos"


def add_text(
    slide,
    text: str,
    x: float,
    y: float,
    w: float,
    h: float,
    size: int = 20,
    color: RGBColor = TEXT,
    bold: bool = False,
    align=PP_ALIGN.LEFT,
) -> None:
    box = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    frame = box.text_frame
    frame.clear()
    frame.word_wrap = True
    frame.vertical_anchor = MSO_ANCHOR.MIDDLE
    paragraph = frame.paragraphs[0]
    paragraph.alignment = align
    run = paragraph.add_run()
    run.text = text
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = color


def add_background(prs: Presentation, title: str, number: int):
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = BG
    add_text(slide, "SPINDLE NADI  /  FEEL THE PULSE. PREDICT THE FAILURE.", 0.55, 0.2, 12.1, 0.35, 10, ACCENT, True)
    add_text(slide, title, 0.55, 0.72, 12.1, 0.7, 28, TEXT, True)
    add_text(slide, f"{number:02d}", 12.15, 7.08, 0.55, 0.25, 10, MUTED, align=PP_ALIGN.RIGHT)
    return slide


def add_panel(slide, title: str, body: str, x: float, y: float, w: float, h: float, color=ACCENT) -> None:
    shape = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE,
        Inches(x),
        Inches(y),
        Inches(w),
        Inches(h),
    )
    shape.fill.solid()
    shape.fill.fore_color.rgb = PANEL
    shape.line.color.rgb = color
    add_text(slide, title, x + 0.2, y + 0.12, w - 0.4, 0.42, 17, color, True)
    add_text(slide, body, x + 0.2, y + 0.65, w - 0.4, h - 0.78, 13, TEXT)


def create_deck() -> Path:
    data_path = Path(DEFAULT_OUTPUT)
    if not data_path.exists():
        generate_dataset(data_path)
    readings = pd.read_csv(data_path)
    if REQUIRED_SENSOR_COLUMNS.difference(readings.columns):
        readings = generate_dataset(data_path)
    pipeline = SpindleNadiPipeline(readings)
    metrics = pipeline.metrics
    states = readings["status"].value_counts().to_dict()

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    slide = prs.slides.add_slide(prs.slide_layouts[6])
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = BG
    add_text(slide, "SPINDLE NADI", 0.8, 1.45, 11.8, 0.8, 24, ACCENT, True, PP_ALIGN.CENTER)
    add_text(slide, "Feel the Pulse.\nPredict the Failure.", 0.8, 2.25, 11.8, 1.8, 38, TEXT, True, PP_ALIGN.CENTER)
    add_text(slide, "Synthetic-data machine-health monitoring prototype", 1.0, 4.45, 11.3, 0.65, 19, MUTED, align=PP_ALIGN.CENTER)
    add_text(slide, "PROJECT DEMONSTRATION", 1.0, 6.7, 11.3, 0.35, 11, ACCENT, True, PP_ALIGN.CENTER)

    slide = add_background(prs, "The problem", 2)
    add_panel(slide, "Gradual degradation", "Machine condition changes over time, not only at the instant a fixed alarm limit is crossed.", 0.7, 1.8, 5.8, 1.8, YELLOW)
    add_panel(slide, "Signals are connected", "Machine load, multi-axis vibration, temperatures, flow, pressure, sound, and trends need operating context.", 6.85, 1.8, 5.8, 1.8)
    add_text(slide, "Goal: turn changing sensor behavior into an understandable reason to investigate.", 1.0, 4.4, 11.3, 0.85, 23, TEXT, True, PP_ALIGN.CENTER)

    slide = add_background(prs, "One connected workflow", 3)
    stages = [
        ("SIMULATE", "Sensor time series"),
        ("ENGINEER", "Workload + RPM + trends"),
        ("ANALYZE", "Anomaly + risk"),
        ("EXPLAIN", "WHY + prototype RUL"),
        ("ACT", "Alert + history"),
    ]
    for index, (heading, caption) in enumerate(stages):
        x = 0.55 + index * 2.57
        add_panel(slide, heading, caption, x, 2.45, 2.3, 1.75)
        if index < len(stages) - 1:
            add_text(slide, "›", x + 2.28, 2.92, 0.35, 0.55, 28, ACCENT, True, PP_ALIGN.CENTER)
    add_text(slide, "The application is a prototype; its inputs and labels are generated by our simulator.", 0.85, 5.2, 11.7, 0.65, 15, MUTED, align=PP_ALIGN.CENTER)

    slide = add_background(prs, "Simulator and data", 4)
    add_panel(slide, "Sensor channels", "XYZ vibration · spindle load/torque · bearing · cooling/lubrication · acoustic/feed · estimated tool wear/power", 0.7, 1.65, 5.8, 1.65)
    add_panel(slide, "Scenarios", "Five injected signatures: bearing · cooling · lubrication · tool wear · spindle imbalance", 6.85, 1.65, 5.8, 1.65, YELLOW)
    state_line = "  |  ".join(f"{state}: {states.get(state, 0)}" for state in ("NORMAL", "WARNING", "CRITICAL"))
    add_text(slide, f"{len(readings)} generated readings · {readings['machine_id'].nunique()} machines · {state_line}", 0.8, 4.05, 11.8, 0.8, 16, ACCENT, True, PP_ALIGN.CENTER)
    add_text(slide, "Operating-point-adjusted deviations, rolling means, five-sample slopes, and RPM variability provide context.", 1.0, 5.2, 11.3, 0.7, 15, MUTED, align=PP_ALIGN.CENTER)

    slide = add_background(prs, "Dashboard and response", 5)
    add_panel(slide, "Monitor", "One-second synthetic stream, sensor-quality checks, risk, prototype health score, anomaly score, and benchmark CSV replay.", 0.7, 1.7, 5.8, 1.8)
    add_panel(slide, "Understand", "Local feature contributions, prototype remaining-life estimate, and held-out evaluation.", 6.85, 1.7, 5.8, 1.8)
    add_panel(slide, "Respond", "Maintenance advice, downloadable evidence report, dashboard alerts, optional email/WhatsApp, and recovery history.", 3.8, 4.15, 5.8, 1.8, YELLOW)

    slide = add_background(prs, "Differentiate through the operator loop", 6)
    add_panel(slide, "What-if", "Project paired workload and RPM settings without changing live machine state.", 0.55, 1.7, 3.0, 1.85)
    add_panel(slide, "Maintenance copilot", "Turn current model evidence into a local, explainable action suggestion.", 3.75, 1.7, 3.0, 1.85, YELLOW)
    add_panel(slide, "Alert → recovery", "Critical sends configured channels; verified virtual recovery is logged and messaged.", 6.95, 1.7, 3.0, 1.85, RED)
    add_panel(slide, "Twin + timeline", "Map evidence to a machine schematic and review recorded events.", 10.15, 1.7, 2.65, 1.85)
    add_text(slide, "A demonstration of decisions, not just a model score. All guidance and maintenance are simulated.", 0.8, 4.5, 11.8, 0.8, 17, MUTED, True, PP_ALIGN.CENTER)

    slide = add_background(prs, "Measured synthetic-data evaluation", 7)
    metric_items = [
        ("Risk MAE", f"{metrics['mae']:.3f}"),
        ("Precision", f"{metrics['precision']:.2f}"),
        ("Recall", f"{metrics['recall']:.2f}"),
        ("F1 score", f"{metrics['f1']:.2f}"),
    ]
    for index, (label, value) in enumerate(metric_items):
        add_panel(slide, label, value, 0.65 + index * 3.15, 1.9, 2.85, 1.45)
    add_text(slide, f"Test set: {int(metrics['test_samples'])} readings from {int(metrics['test_machines'])} held-out machines.", 0.9, 4.0, 11.5, 0.55, 16, TEXT, True, PP_ALIGN.CENTER)
    add_text(slide, "Numbers describe generated data only. They do not establish real-machine accuracy or lead time.", 0.9, 4.8, 11.5, 0.75, 16, YELLOW, True, PP_ALIGN.CENTER)

    slide = add_background(prs, "WHY, RUL, and maintenance", 8)
    add_panel(slide, "WHY", "Estimate contributions by restoring one feature at a time to its healthy reference.", 0.7, 1.8, 3.8, 2.1)
    add_panel(slide, "Last Good Hour", "Extrapolate the simulator's fixed degradation rate. This is not a failure-time guarantee.", 4.75, 1.8, 3.8, 2.1, YELLOW)
    add_panel(slide, "Maintenance", "Record a higher-risk transition and link inspection suggestions to the top model factors.", 8.8, 1.8, 3.8, 2.1, RED)
    add_text(slide, "No real-machine lifetime, safety, or causal claims are made.", 0.9, 4.8, 11.5, 0.65, 17, MUTED, True, PP_ALIGN.CENTER)

    slide = add_background(prs, "Limitations and next steps", 9)
    add_panel(slide, "Today", "Reproducible synthetic data · simple interpretable pipeline · interactive local demo", 0.7, 1.7, 5.8, 1.8)
    add_panel(slide, "Next", "Connect validated sensors and maintenance labels; assess drift, false alarms, and machine-specific behavior.", 6.85, 1.7, 5.8, 1.8, YELLOW)
    add_text(slide, "Traditional monitoring asks: “Did we cross a limit?”\nSpindle Nadi explores: “Are signals getting worse, and why?”", 1.0, 4.35, 11.3, 1.25, 22, TEXT, True, PP_ALIGN.CENTER)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    prs.save(OUTPUT)
    return OUTPUT


if __name__ == "__main__":
    print(f"Created presentation: {create_deck()}")
